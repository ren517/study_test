r1 = 15.0  # 下底面半径
r2 = 10.0  # 上底面半径
h = 9.3  # 高
pi = 3.141592653589793  # π 值

s = (h**2 + (r1 - r2) ** 2) ** 0.5  # 母线长
print("圆台的母线长为：", s)

# 侧面积
A1 = pi * (r1 + r2) * s
print(f"圆台的侧面积:{A1}")

# 全面积
A2 = A1 + pi * (r1**2 + r2**2)

# 体积
V = pi * h / 3 * (r1**2 + 2 * r1 * r2 + r2**2.0)
print(f"圆台的体积为:{V}")
